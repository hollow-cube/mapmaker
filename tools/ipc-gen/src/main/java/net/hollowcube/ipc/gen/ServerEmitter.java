package net.hollowcube.ipc.gen;

import com.palantir.javapoet.*;
import org.jetbrains.annotations.Nullable;

import javax.annotation.processing.Messager;
import javax.lang.model.element.Modifier;
import java.io.IOException;
import java.io.InputStreamReader;
import java.io.Reader;
import java.lang.reflect.Type;
import java.nio.charset.StandardCharsets;

/// Emits `<Name>Server`: a [com.sun.net.httpserver.HttpHandler] over any implementation of the
/// interface.
///
/// Mount it at [IpcModel#path] — `server.createContext(FooServer.PATH, new FooServer(impl, gson))`
/// — and the trailing path segment selects the method. Routing is a `switch` over string literals
/// the processor also wrote into the client, so the two cannot drift.
final class ServerEmitter {

    private static final ClassName GSON = ClassName.get("com.google.gson", "Gson");
    private static final ClassName HTTP_EXCHANGE = ClassName.get("com.sun.net.httpserver", "HttpExchange");
    private static final ClassName HTTP_HANDLER = ClassName.get("com.sun.net.httpserver", "HttpHandler");
    private static final ClassName JSON_ELEMENT = ClassName.get("com.google.gson", "JsonElement");
    private static final ClassName JSON_OBJECT = ClassName.get("com.google.gson", "JsonObject");
    private static final ClassName JSON_PARSER = ClassName.get("com.google.gson", "JsonParser");
    private static final ClassName OPEN_TELEMETRY = ClassName.get("io.opentelemetry.api", "OpenTelemetry");

    static @Nullable TypeSpec emit(Messager messager, IpcModel model) {
        var type = TypeSpec.classBuilder(model.serverName())
            .addJavadoc("Serves {@link $T} over HTTP. Generated by {@code IpcProcessor}.\n",
                model.interfaceName())
            .addAnnotation(AnnotationSpec.builder(ClassName.get("javax.annotation.processing", "Generated"))
                .addMember("value", "$S", IpcProcessor.class.getName())
                .build())
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addSuperinterface(HTTP_HANDLER)
            .addField(FieldSpec.builder(String.class, "PATH", Modifier.PUBLIC, Modifier.STATIC, Modifier.FINAL)
                .addJavadoc("Path to mount this handler at.\n")
                .initializer("$S", model.path())
                .build())
            .addField(model.interfaceName(), "impl", Modifier.PRIVATE, Modifier.FINAL)
            .addField(GSON, "gson", Modifier.PRIVATE, Modifier.FINAL)
            .addField(IpcNames.IPC_TRACING, "tracing", Modifier.PRIVATE, Modifier.FINAL);

        type.addMethod(MethodSpec.constructorBuilder()
            .addJavadoc("An untraced server, for a process that has no {@link $T}.\n", OPEN_TELEMETRY)
            .addModifiers(Modifier.PUBLIC)
            .addParameter(model.interfaceName(), "impl")
            .addParameter(GSON, "gson")
            .addStatement("this(impl, gson, $T.noop())", OPEN_TELEMETRY)
            .build());

        type.addMethod(MethodSpec.constructorBuilder()
            .addModifiers(Modifier.PUBLIC)
            .addParameter(model.interfaceName(), "impl")
            .addParameter(GSON, "gson")
            .addParameter(OPEN_TELEMETRY, "otel")
            .addStatement("this.impl = impl")
            .addStatement("this.gson = gson")
            .addStatement("this.tracing = new $T(otel, $S)", IpcNames.IPC_TRACING, model.serviceName())
            .build());

        var dispatch = CodeBlock.builder().beginControlFlow("switch (ipcMethod)");
        for (var method : model.methods()) {
            dispatch.beginControlFlow("case $S ->", method.route());

            var arguments = CodeBlock.builder();
            for (int i = 0; i < method.parameters().size(); i++) {
                var parameter = method.parameters().get(i);
                var parameterType = GsonTypes.runtimeType(messager, parameter, parameter.asType());
                if (parameterType == null) return null;
                if (GsonTypes.isParameterized(parameter.asType())) {
                    var constant = "TYPE_" + method.name() + "_" + parameter.getSimpleName();
                    type.addField(FieldSpec.builder(Type.class, constant,
                        Modifier.PRIVATE, Modifier.STATIC, Modifier.FINAL).initializer(parameterType).build());
                    parameterType = CodeBlock.of("$N", constant);
                }
                dispatch.addStatement("$T $N = gson.fromJson(ipcRequest.get($S), $L)",
                    TypeName.get(parameter.asType()), parameter.getSimpleName(),
                    parameter.getSimpleName(), parameterType);
                if (i > 0) arguments.add(", ");
                arguments.add("$N", parameter.getSimpleName());
            }

            if (method.isVoid()) {
                dispatch.addStatement("impl.$N($L)", method.name(), arguments.build());
                dispatch.addStatement("ipcResponse = null");
            } else {
                var returnType = GsonTypes.runtimeType(messager, method.element(), method.returnType());
                if (returnType == null) return null;
                if (GsonTypes.isParameterized(method.returnType())) {
                    var constant = "TYPE_" + method.name();
                    type.addField(FieldSpec.builder(Type.class, constant,
                        Modifier.PRIVATE, Modifier.STATIC, Modifier.FINAL).initializer(returnType).build());
                    returnType = CodeBlock.of("$N", constant);
                }
                dispatch.addStatement("ipcResponse = gson.toJsonTree(impl.$N($L), $L)",
                    method.name(), arguments.build(), returnType);
            }

            dispatch.endControlFlow();
        }
        dispatch.beginControlFlow("default ->")
            .addStatement("respondError(exchange, span, 404, $S + ipcMethod + $S)", "no such method '", "'")
            .addStatement("return")
            .endControlFlow()
            .endControlFlow();

        return type
            .addMethod(handleMethod(dispatch.build()))
            .addMethod(respondMethod())
            .addMethod(respondErrorMethod())
            .build();
    }

    private static MethodSpec handleMethod(CodeBlock dispatch) {
        return MethodSpec.methodBuilder("handle")
            .addAnnotation(Override.class)
            .addModifiers(Modifier.PUBLIC)
            .addParameter(HTTP_EXCHANGE, "exchange")
            .addException(IOException.class)
            .addStatement("String ipcPath = exchange.getRequestURI().getPath()")
            .addStatement("String ipcMethod = ipcPath.substring(ipcPath.lastIndexOf('/') + 1)")
            .beginControlFlow("try ($T span = tracing.server(ipcMethod, exchange))", IpcNames.IPC_SPAN)
            .beginControlFlow("try")
            .beginControlFlow("if (!$S.equals(exchange.getRequestMethod()))", "POST")
            .addStatement("respondError(exchange, span, 405, $S)", "ipc calls are POST")
            .addStatement("return")
            .endControlFlow()
            .addStatement("$T ipcRequest", JSON_OBJECT)
            .beginControlFlow("try ($T ipcReader = new $T(exchange.getRequestBody(), $T.UTF_8))",
                Reader.class, InputStreamReader.class, StandardCharsets.class)
            .addStatement("$T ipcBody = $T.parseReader(ipcReader)", JSON_ELEMENT, JSON_PARSER)
            .addStatement("ipcRequest = ipcBody.isJsonObject() ? ipcBody.getAsJsonObject() : new $T()", JSON_OBJECT)
            .endControlFlow()
            .addStatement("$T ipcResponse", JSON_ELEMENT)
            .addCode(dispatch)
            .addStatement("respond(exchange, span, ipcResponse == null ? 204 : 200, ipcResponse)")
            .nextControlFlow("catch ($T e)", IpcNames.IPC_EXCEPTION)
            .addStatement("respondError(exchange, span, e.status() >= 400 && e.status() < 600 ? e.status() : 500, String.valueOf(e.getMessage()))")
            // Exception rather than RuntimeException: a service that reaches sql-gen reaches its
            // sneaky-thrown SQLException too, and letting that escape `handle` drops the connection
            // without a response instead of answering 500.
            .nextControlFlow("catch ($T e)", Exception.class)
            .addStatement("span.failed(e)")
            .addStatement("respondError(exchange, span, 500, e.toString())")
            .nextControlFlow("finally")
            .addStatement("exchange.close()")
            .endControlFlow()
            .endControlFlow()
            .build();
    }

    private static MethodSpec respondMethod() {
        return MethodSpec.methodBuilder("respond")
            .addModifiers(Modifier.PRIVATE, Modifier.STATIC)
            .addParameter(HTTP_EXCHANGE, "exchange")
            .addParameter(IpcNames.IPC_SPAN, "span")
            .addParameter(TypeName.INT, "status")
            .addParameter(JSON_ELEMENT, "body")
            .addException(IOException.class)
            .addStatement("span.status(status)")
            .addStatement("byte[] bytes = body == null ? new byte[0] : body.toString().getBytes($T.UTF_8)",
                StandardCharsets.class)
            .addStatement("exchange.getResponseHeaders().set($S, $S)", "Content-Type", "application/json")
            .addStatement("exchange.sendResponseHeaders(status, bytes.length == 0 ? -1 : bytes.length)")
            .beginControlFlow("if (bytes.length > 0)")
            .addStatement("exchange.getResponseBody().write(bytes)")
            .endControlFlow()
            .build();
    }

    private static MethodSpec respondErrorMethod() {
        return MethodSpec.methodBuilder("respondError")
            .addModifiers(Modifier.PRIVATE, Modifier.STATIC)
            .addParameter(HTTP_EXCHANGE, "exchange")
            .addParameter(IpcNames.IPC_SPAN, "span")
            .addParameter(TypeName.INT, "status")
            .addParameter(String.class, "message")
            .addException(IOException.class)
            .addStatement("$T error = new $T()", JSON_OBJECT, JSON_OBJECT)
            .addStatement("error.addProperty($S, message)", "error")
            .addStatement("respond(exchange, span, status, error)")
            .build();
    }

    private ServerEmitter() {
    }
}
