package net.hollowcube.ipc.gen;

import com.palantir.javapoet.*;
import org.jetbrains.annotations.Nullable;

import javax.annotation.processing.Messager;
import javax.lang.model.element.Modifier;
import java.io.IOException;
import java.lang.reflect.Type;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;

/// Emits `<Interface>Http`: the interface, implemented by posting one JSON request per method.
///
/// The generated class talks to `java.net.http` directly rather than through a transport
/// abstraction. There is nothing for a transport to vary — every method is `POST
/// /<service>/<method-name>` with a JSON object in and a JSON value out — and keeping it concrete
/// means the only non-JDK types the output touches are Gson and [IpcNames#IPC_EXCEPTION].
final class ClientEmitter {

    private static final ClassName GSON = ClassName.get("com.google.gson", "Gson");
    private static final ClassName OPEN_TELEMETRY = ClassName.get("io.opentelemetry.api", "OpenTelemetry");
    private static final ClassName JSON_ELEMENT = ClassName.get("com.google.gson", "JsonElement");
    private static final ClassName JSON_NULL = ClassName.get("com.google.gson", "JsonNull");
    private static final ClassName JSON_OBJECT = ClassName.get("com.google.gson", "JsonObject");
    private static final ClassName JSON_PARSER = ClassName.get("com.google.gson", "JsonParser");

    static @Nullable TypeSpec emit(Messager messager, IpcModel model) {
        var type = TypeSpec.classBuilder(model.clientName())
            .addJavadoc("Calls {@link $T} over HTTP. Generated by {@code IpcProcessor}.\n",
                model.interfaceName())
            .addAnnotation(AnnotationSpec.builder(ClassName.get("javax.annotation.processing", "Generated"))
                .addMember("value", "$S", IpcProcessor.class.getName())
                .build())
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addSuperinterface(model.interfaceName())
            .addField(FieldSpec.builder(String.class, "PATH", Modifier.PUBLIC, Modifier.STATIC, Modifier.FINAL)
                .addJavadoc("Path prefix every method of this client posts to.\n")
                .initializer("$S", model.path())
                .build())
            .addField(HttpClient.class, "httpClient", Modifier.PRIVATE, Modifier.FINAL)
            .addField(GSON, "gson", Modifier.PRIVATE, Modifier.FINAL)
            .addField(String.class, "baseUrl", Modifier.PRIVATE, Modifier.FINAL)
            .addField(IpcNames.IPC_TRACING, "tracing", Modifier.PRIVATE, Modifier.FINAL);

        type.addMethod(MethodSpec.constructorBuilder()
            .addJavadoc("An untraced client, for a caller that has no {@link $T}.\n", OPEN_TELEMETRY)
            .addModifiers(Modifier.PUBLIC)
            .addParameter(HttpClient.class, "httpClient")
            .addParameter(GSON, "gson")
            .addParameter(String.class, "baseUrl")
            .addStatement("this(httpClient, gson, baseUrl, $T.noop())", OPEN_TELEMETRY)
            .build());

        type.addMethod(MethodSpec.constructorBuilder()
            .addJavadoc("@param baseUrl root the service is served under; a trailing slash is ignored.\n")
            .addModifiers(Modifier.PUBLIC)
            .addParameter(HttpClient.class, "httpClient")
            .addParameter(GSON, "gson")
            .addParameter(String.class, "baseUrl")
            .addParameter(OPEN_TELEMETRY, "otel")
            .addStatement("this.httpClient = httpClient")
            .addStatement("this.gson = gson")
            .addStatement("this.baseUrl = baseUrl.endsWith($S) ? baseUrl.substring(0, baseUrl.length() - 1) : baseUrl", "/")
            .addStatement("this.tracing = new $T(otel, $S)", IpcNames.IPC_TRACING, model.serviceName())
            .build());

        for (var method : model.methods()) {
            var body = CodeBlock.builder()
                .addStatement("$T ipcRequest = new $T()", JSON_OBJECT, JSON_OBJECT);
            for (var parameter : method.parameters()) {
                var parameterType = GsonTypes.runtimeType(messager, parameter, parameter.asType());
                if (parameterType == null) return null;
                body.addStatement("ipcRequest.add($S, gson.toJsonTree($N, $L))",
                    parameter.getSimpleName(), parameter.getSimpleName(), parameterType);
            }

            if (method.isVoid()) {
                body.addStatement("call($S, ipcRequest)", method.route());
            } else {
                var returnType = GsonTypes.runtimeType(messager, method.element(), method.returnType());
                if (returnType == null) return null;
                if (GsonTypes.isParameterized(method.returnType())) {
                    var constant = "TYPE_" + method.name();
                    type.addField(FieldSpec.builder(Type.class, constant,
                        Modifier.PRIVATE, Modifier.STATIC, Modifier.FINAL).initializer(returnType).build());
                    returnType = CodeBlock.of("$N", constant);
                }
                body.addStatement("return gson.fromJson(call($S, ipcRequest), $L)", method.route(), returnType);
            }

            type.addMethod(MethodSpec.overriding(method.element()).addCode(body.build()).build());
        }

        return type.addMethod(callMethod()).build();
    }

    /// The one piece of plumbing, shared by every method of the client.
    ///
    /// The span opens before the request is built because opening it is also what writes the
    /// propagation headers onto the builder, and closes before the response is read because the
    /// span covers the call, not what the caller does with the answer.
    private static MethodSpec callMethod() {
        return MethodSpec.methodBuilder("call")
            .addModifiers(Modifier.PRIVATE)
            .returns(JSON_ELEMENT)
            .addParameter(String.class, "method")
            .addParameter(JSON_OBJECT, "request")
            .addStatement("String url = baseUrl + PATH + $S + method", "/")
            .addStatement("$T.Builder httpRequest = $T.newBuilder($T.create(url))\n"
                    + "    .header($S, $S)\n"
                    + "    .POST($T.BodyPublishers.ofString(request.toString(), $T.UTF_8))",
                HttpRequest.class, HttpRequest.class, URI.class,
                "Content-Type", "application/json",
                HttpRequest.class, StandardCharsets.class)
            .addStatement("$T<String> response", HttpResponse.class)
            .beginControlFlow("try ($T span = tracing.client(method, httpRequest, url))", IpcNames.IPC_SPAN)
            .beginControlFlow("try")
            .addStatement("response = httpClient.send(httpRequest.build(), $T.BodyHandlers.ofString($T.UTF_8))",
                HttpResponse.class, StandardCharsets.class)
            .nextControlFlow("catch ($T e)", IOException.class)
            .addStatement("span.failed(e)")
            .addStatement("throw new $T(0, url + $S + e, e)", IpcNames.IPC_EXCEPTION, " failed: ")
            .nextControlFlow("catch ($T e)", InterruptedException.class)
            .addStatement("$T.currentThread().interrupt()", Thread.class)
            .addStatement("span.failed(e)")
            .addStatement("throw new $T(0, url + $S, e)", IpcNames.IPC_EXCEPTION, " interrupted")
            .endControlFlow()
            .addStatement("span.status(response.statusCode())")
            .endControlFlow()
            .beginControlFlow("if (response.statusCode() < 200 || response.statusCode() >= 300)")
            .addStatement("throw new $T(response.statusCode(), url + $S + response.statusCode() + $S + response.body())",
                IpcNames.IPC_EXCEPTION, " answered ", ": ")
            .endControlFlow()
            .addStatement("String body = response.body()")
            .addStatement("return body == null || body.isBlank() ? $T.INSTANCE : $T.parseString(body)",
                JSON_NULL, JSON_PARSER)
            .build();
    }

    private ClientEmitter() {
    }
}
