package net.hollowcube.ipc.gen;

import com.palantir.javapoet.*;

import javax.lang.model.element.Modifier;
import java.io.IOException;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

/// Emits `net.hollowcube.ipc.WireAdapters`, the [com.google.gson.TypeAdapterFactory] behind
/// `Wire.gson()`, with one adapter per wire enum and sealed interface nested inside it — and the
///
/// Records need no adapter: gson's reflective one already reads and writes them by component
/// name, and a field it does not know is ignored, which is what makes adding one safe. Enums and
/// sealed types are where gson's defaults fail closed — an unknown constant is an exception — so
/// they get adapters that fail open into `UNKNOWN`, and refuse to write it back out.
final class AdaptersEmitter {

    private static final ClassName GSON = ClassName.get("com.google.gson", "Gson");
    private static final ClassName TYPE_ADAPTER = ClassName.get("com.google.gson", "TypeAdapter");
    private static final ClassName TYPE_ADAPTER_FACTORY = ClassName.get("com.google.gson", "TypeAdapterFactory");
    private static final ClassName TYPE_TOKEN = ClassName.get("com.google.gson.reflect", "TypeToken");
    private static final ClassName JSON_READER = ClassName.get("com.google.gson.stream", "JsonReader");
    private static final ClassName JSON_WRITER = ClassName.get("com.google.gson.stream", "JsonWriter");
    private static final ClassName JSON_TOKEN = ClassName.get("com.google.gson.stream", "JsonToken");
    private static final ClassName JSON_ELEMENT = ClassName.get("com.google.gson", "JsonElement");
    private static final ClassName JSON_OBJECT = ClassName.get("com.google.gson", "JsonObject");
    private static final ClassName JSON_PARSER = ClassName.get("com.google.gson", "JsonParser");
    private static final ClassName JSON_SYNTAX_EXCEPTION = ClassName.get("com.google.gson", "JsonSyntaxException");
    private static final ClassName NULLABLE = ClassName.get("org.jetbrains.annotations", "Nullable");

    static TypeSpec factory(WireWalker walker) {
        var type = TypeSpec.classBuilder(IpcNames.WIRE_ADAPTERS)
            .addJavadoc("Every adapter {@code Wire.gson()} carries: one per wire enum and sealed interface. "
                + "Generated by {@code IpcProcessor}.\n")
            .addAnnotation(generated())
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addSuperinterface(TYPE_ADAPTER_FACTORY);

        var typeVariable = TypeVariableName.get("T");
        var create = MethodSpec.methodBuilder("create")
            .addAnnotation(Override.class)
            .addAnnotation(AnnotationSpec.builder(SuppressWarnings.class).addMember("value", "$S", "unchecked").build())
            .addModifiers(Modifier.PUBLIC)
            .addTypeVariable(typeVariable)
            .returns(ParameterizedTypeName.get(TYPE_ADAPTER, typeVariable))
            .addParameter(GSON, "gson")
            .addParameter(ParameterizedTypeName.get(TYPE_TOKEN, typeVariable), "type");
        if (!walker.enums().isEmpty() || !walker.sealeds().isEmpty()) {
            create.addStatement("$T<? super T> raw = type.getRawType()", Class.class);
        }

        var names = new HashSet<String>();
        for (var wireEnum : walker.enums()) {
            var target = ClassName.get(wireEnum.element());
            var adapter = adapterName(names, target);
            create.addStatement("if (raw == $T.class) return ($T<T>) new $N()", target, TYPE_ADAPTER, adapter);
            type.addType(enumAdapter(adapter, target, wireEnum.constants()));
        }
        for (var sealed : walker.sealeds()) {
            var target = ClassName.get(sealed.element());
            var adapter = adapterName(names, target);
            create.addStatement("if (raw == $T.class) return ($T<T>) new $N(gson)", target, TYPE_ADAPTER, adapter);
            type.addType(sealedAdapter(adapter, target, sealed));
        }
        create.addStatement("return null");
        return type.addMethod(create.build()).build();
    }

    private static TypeSpec enumAdapter(String name, ClassName target, List<String> constants) {
        var read = MethodSpec.methodBuilder("read")
            .addAnnotation(Override.class)
            .addModifiers(Modifier.PUBLIC)
            .returns(target)
            .addParameter(JSON_READER, "in")
            .addException(IOException.class)
            .beginControlFlow("if (in.peek() == $T.NULL)", JSON_TOKEN)
            .addStatement("in.nextNull()")
            .addStatement("return null")
            .endControlFlow()
            .beginControlFlow("return switch (in.nextString())");
        for (var constant : constants) {
            read.addStatement("case $S -> $T.$N", constant, target, constant);
        }
        read.addStatement("default -> $T.$N", target, IpcNames.UNKNOWN_CONSTANT)
            .endControlFlow("");

        return TypeSpec.classBuilder(name)
            .addModifiers(Modifier.STATIC, Modifier.FINAL)
            .superclass(ParameterizedTypeName.get(TYPE_ADAPTER, target))
            .addMethod(MethodSpec.methodBuilder("write")
                .addAnnotation(Override.class)
                .addModifiers(Modifier.PUBLIC)
                .addParameter(JSON_WRITER, "out")
                .addParameter(target, "value")
                .addException(IOException.class)
                .beginControlFlow("if (value == null)")
                .addStatement("out.nullValue()")
                .addStatement("return")
                .endControlFlow()
                .beginControlFlow("if (value == $T.$N)", target, IpcNames.UNKNOWN_CONSTANT)
                .addStatement("throw new $T($S)", IllegalArgumentException.class,
                    target.simpleName() + "." + IpcNames.UNKNOWN_CONSTANT
                        + " is what a constant this build does not know reads as; it cannot be written back")
                .endControlFlow()
                .addStatement("out.value(value.name())")
                .build())
            .addMethod(read.build())
            .build();
    }

    private static TypeSpec sealedAdapter(String name, ClassName target, WireWalker.WireSealed sealed) {
        var write = MethodSpec.methodBuilder("write")
            .addAnnotation(Override.class)
            .addModifiers(Modifier.PUBLIC)
            .addParameter(JSON_WRITER, "out")
            .addParameter(target, "value")
            .addException(IOException.class)
            .beginControlFlow("if (value == null)")
            .addStatement("out.nullValue()")
            .addStatement("return")
            .endControlFlow()
            .addStatement("$T json = new $T()", JSON_OBJECT, JSON_OBJECT)
            .beginControlFlow("switch (value)");
        for (var variant : sealed.variants().entrySet()) {
            var variantType = ClassName.get(variant.getValue());
            write.beginControlFlow("case $T v ->", variantType)
                .addStatement("json.addProperty($S, $S)", IpcNames.DISCRIMINATOR, variant.getKey())
                .addStatement("json.asMap().putAll(gson.toJsonTree(v, $T.class).getAsJsonObject().asMap())", variantType)
                .endControlFlow();
        }
        write.beginControlFlow("case $T v ->", sealed.unknown())
            .addStatement("throw new $T($S + v.$N() + $S)", IllegalArgumentException.class,
                sealed.unknown().simpleName() + "(", IpcNames.DISCRIMINATOR,
                ") is what a variant this build does not know reads as; it cannot be written back")
            .endControlFlow()
            .endControlFlow()
            .addStatement("gson.toJson(json, out)");

        var read = MethodSpec.methodBuilder("read")
            .addAnnotation(Override.class)
            .addModifiers(Modifier.PUBLIC)
            .returns(target)
            .addParameter(JSON_READER, "in")
            .addException(IOException.class)
            .beginControlFlow("if (in.peek() == $T.NULL)", JSON_TOKEN)
            .addStatement("in.nextNull()")
            .addStatement("return null")
            .endControlFlow()
            .addStatement("$T element = $T.parseReader(in)", JSON_ELEMENT, JSON_PARSER)
            .beginControlFlow("if (!element.isJsonObject())")
            .addStatement("throw new $T($S + element)", JSON_SYNTAX_EXCEPTION,
                "expected an object for " + target.simpleName() + ", got ")
            .endControlFlow()
            .addStatement("$T json = element.getAsJsonObject()", JSON_OBJECT)
            .addStatement("$T discriminator = json.remove($S)", JSON_ELEMENT, IpcNames.DISCRIMINATOR)
            .addStatement("String $N = discriminator == null || !discriminator.isJsonPrimitive() ? null : discriminator.getAsString()",
                IpcNames.DISCRIMINATOR)
            .beginControlFlow("if ($N != null)", IpcNames.DISCRIMINATOR)
            .beginControlFlow("switch ($N)", IpcNames.DISCRIMINATOR);
        for (var variant : sealed.variants().entrySet()) {
            read.beginControlFlow("case $S ->", variant.getKey())
                .addStatement("return gson.fromJson(json, $T.class)", ClassName.get(variant.getValue()))
                .endControlFlow();
        }
        read.beginControlFlow("default ->")
            .endControlFlow()
            .endControlFlow()
            .endControlFlow()
            .addStatement("return new $T($N)", sealed.unknown(), IpcNames.DISCRIMINATOR);

        return TypeSpec.classBuilder(name)
            .addModifiers(Modifier.STATIC, Modifier.FINAL)
            .superclass(ParameterizedTypeName.get(TYPE_ADAPTER, target))
            .addField(GSON, "gson", Modifier.PRIVATE, Modifier.FINAL)
            .addMethod(MethodSpec.constructorBuilder()
                .addParameter(GSON, "gson")
                .addStatement("this.gson = gson")
                .build())
            .addMethod(write.build())
            .addMethod(read.build())
            .build();
    }

    /// `FooAdapter` after the simple names, falling back to the whole package when two wire types
    /// in different packages share a name.
    private static String adapterName(Set<String> taken, ClassName target) {
        var name = String.join("", target.simpleNames()) + "Adapter";
        if (!taken.add(name)) {
            name = target.canonicalName().replace('.', '_') + "Adapter";
            taken.add(name);
        }
        return name;
    }

    private static AnnotationSpec generated() {
        return AnnotationSpec.builder(ClassName.get("javax.annotation.processing", "Generated"))
            .addMember("value", "$S", IpcProcessor.class.getName())
            .build();
    }

    private AdaptersEmitter() {
    }
}
